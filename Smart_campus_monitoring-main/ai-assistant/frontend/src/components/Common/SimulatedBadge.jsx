import React from 'react';
import { AlertTriangle, Sparkles } from 'lucide-react';

/**
 * Visual disclosure badge to guarantee mock data is never mistaken for live sensor data
 */
export default function SimulatedBadge({ variant = 'inline', className = '' }) {
  if (variant === 'banner') {
    return (
      <aside 
        className={`simulated-data-banner ${className}`}
        style={{
          display: 'flex',
          alignItems: 'center',
          gap: '8px',
          padding: '6px 12px',
          backgroundColor: 'var(--campus-terracotta-light)',
          borderBottom: '1px solid #EED4C2',
          fontSize: '0.72rem',
          fontWeight: 600,
          color: '#8A4A1C',
          letterSpacing: '0.02em',
          userSelect: 'none'
        }}
        aria-label="Simulation notice"
      >
        <AlertTriangle size={13} style={{ flexShrink: 0, color: '#C77B45' }} aria-hidden="true" />
        <span>SIMULATED DATA — NOT CONNECTED TO LIVE SENSORS</span>
      </aside>
    );
  }

  // compact/inline tag for individual messages
  return (
    <span
      className={`simulated-data-tag ${className}`}
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        gap: '4px',
        padding: '2px 6px',
        borderRadius: 'var(--radius-sm)',
        backgroundColor: 'var(--campus-terracotta-light)',
        border: '1px solid #EED4C2',
        fontSize: '0.66rem',
        fontWeight: 700,
        color: '#8A4A1C',
        letterSpacing: '0.04em',
        textTransform: 'uppercase'
      }}
      title="This metric was generated by the deterministic campus simulator"
    >
      <Sparkles size={10} aria-hidden="true" />
      Simulated
    </span>
  );
}
